// Extracts the curated subset of Phosphor "Regular" icons used by Soroe from
// the local @iconify-json/ph data and writes it to a static TS module, so the
// app bundles only the icons it uses instead of the full ~9000-icon package.
// Re-run after editing ICON_NAMES: pnpm run icons:generate

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { getIconData } from '@iconify/utils';
import phIcons from '@iconify-json/ph/icons.json' with { type: 'json' };

// Keep in sync with docs/DesignSystem.pdf section 05 (アイコン).
const ICON_NAMES = [
  'house',
  'squares-four',
  'sparkle',
  'gear',
  'shopping-cart-simple',
  'suitcase',
  'check',
  'plus',
  'caret-right',
  'pencil-simple',
  'trash',
  'user-plus',
  'link-simple',
  'bell',
  'globe',
  'user',
  'bookmark-simple',
  'magnifying-glass',
  'arrows-clockwise',
  'wifi-slash',
  'warning',
  'tray',
  'dots-three',
  'magic-wand',
  // LIST-005: リスト詳細の手動並べ替えUI用。
  'caret-up',
  'caret-down',
  'x',
];

const PATH_D_PATTERN = /\sd="([^"]+)"/g;

function extractPathData(bodyMarkup) {
  const paths = [...bodyMarkup.matchAll(PATH_D_PATTERN)].map((match) => match[1]);
  if (paths.length === 0) {
    throw new Error(`No <path d="..."> found in icon body: ${bodyMarkup}`);
  }
  return paths;
}

const entries = ICON_NAMES.map((name) => {
  const iconData = getIconData(phIcons, name);
  if (!iconData) {
    throw new Error(`Icon "ph:${name}" not found in @iconify-json/ph`);
  }
  if (iconData.width !== phIcons.width || iconData.height !== phIcons.height) {
    throw new Error(`Icon "ph:${name}" has a non-standard viewBox; update generate-ph-icons.mjs`);
  }
  return [name, extractPathData(iconData.body)];
});

const iconRecordLiteral = entries
  .map(([name, paths]) => `  '${name}': [${paths.map((d) => JSON.stringify(d)).join(', ')}],`)
  .join('\n');

const output = `// Generated by scripts/generate-ph-icons.mjs — do not edit by hand.
// Source: @iconify-json/ph (Phosphor "Regular" style, viewBox 0 0 ${phIcons.width} ${phIcons.height}).

export const PH_ICON_VIEWBOX_SIZE = ${phIcons.width};

export const phIconPaths = {
${iconRecordLiteral}
} as const;

export type PhIconName = keyof typeof phIconPaths;

export function isPhIconName(value: string): value is PhIconName {
  return value in phIconPaths;
}
`;

const outFile = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/design-system/icons/ph-icon-paths.ts'
);
writeFileSync(outFile, output);
console.log(`Wrote ${entries.length} icons to ${path.relative(process.cwd(), outFile)}`);
